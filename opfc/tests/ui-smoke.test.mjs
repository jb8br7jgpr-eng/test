import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';

test('La page OPFC charge son propre CSS et son propre module, sans modifier la page classique',()=>{
 const root=new URL('../../opfc.html',import.meta.url);
 const html=readFileSync(root,'utf8');
 assert.match(html,/opfc\/ui\.css/);
 assert.match(html,/opfc\/ui\.mjs/);
 assert.match(html,/viewport-fit=cover/);
 assert.match(html,/id="opfc-app"/);
 assert.doesNotMatch(html,/classique\.html.*<script/);
});
test('Module interface et modèle valides pour Node et navigateur (syntaxe)',()=>{
 for(const p of ['../ui.mjs','../ui-model.mjs']){
  const full=fileURLToPath(new URL(p,import.meta.url));
  assert.ok(existsSync(full));
  execFileSync(process.execPath,['--check',full]);
 }
 const css=readFileSync(new URL('../ui.css',import.meta.url),'utf8');
 assert.match(css,/safe-area-inset-top/);
 assert.match(css,/\.slot-field/);
 assert.match(css,/\.player-card/);
 assert.match(css,/\.modal-backdrop/);
 assert.match(css,/@media/);
});
test('L’interface démarre sans erreur, gère le choix du club et lance un mercato réel',async()=>{
 const callbacks={},cache=new Map(),root={innerHTML:'',addEventListener:(type,fn)=>{callbacks[type]=fn;}};
 globalThis.document={getElementById:id=>id==='opfc-app'?root:id==='bid-value'?{value:'5000000'}:null};
 globalThis.localStorage={getItem:key=>cache.get(key)??null,setItem:(key,value)=>cache.set(key,value),removeItem:key=>cache.delete(key)};
 await import('../ui.mjs');
 assert.match(root.innerHTML,/La Grandline Cup/);
 assert.match(root.innerHTML,/Mode en ligne · salons privés/);
 const press=(action,extra={})=>{
  const btn={dataset:{action,...extra},disabled:false};
  callbacks.click({target:{closest:()=>btn}});
 };
 press('online');
 assert.match(root.innerHTML,/Créer une partie/);
 press('online-join-screen');
 assert.match(root.innerHTML,/Code à 6 caractères/);
 assert.match(root.innerHTML,/n’est pas encore déployé/);
 press('online-back');
 press('online-back');
 assert.match(root.innerHTML,/La Grandline Cup/);
 press('club',{club:'OM'});
 assert.match(root.innerHTML,/club-option om active/);
 press('start');
 assert.match(root.innerHTML,/Départ du mercato/);
 const stored=JSON.parse(cache.get('opfc-v08-local-dev'));
 assert.equal(stored.game.phase,'mercato');
 assert.equal(stored.firstClub,'OM');
 assert.equal(stored.game.teams[0].club,'OM');
 assert.equal(stored.game.teams.length,2);
 press('close');
 assert.match(root.innerHTML,/Mercato des légendes/);
 assert.doesNotMatch(root.innerHTML,/slot-field/);
 assert.match(root.innerHTML,/Voir les équipes/);
 press('toggle-teams');
 assert.match(root.innerHTML,/slot-field/);
 press('toggle-teams');
 assert.match(root.innerHTML,/👁 Observation/);
 assert.match(root.innerHTML,/👑 Haki des Rois/);
 assert.match(root.innerHTML,/Refus utilisés :/);
 assert.match(root.innerHTML,/Restants :/);
 assert.match(root.innerHTML,/data-amount="6"/);
 assert.match(root.innerHTML,/5 000 000 ฿/);
 assert.match(root.innerHTML,/250 000 000 ฿/);
 assert.match(root.innerHTML,/class="auction-hakis"/);
 const first=stored.game.auction.turn;
 press('observation');
 assert.match(root.innerHTML,/Choix secret/);
 assert.equal(JSON.parse(cache.get('opfc-v08-local-dev')).game.teams.find(t=>t.club===first).hakis.observation,true);
 press('observation-show');
 assert.match(root.innerHTML,/preview-list/);
 press('close');
 assert.match(root.innerHTML,/Mercato des légendes/);
 // Vraie vente depuis l'écran, puis placement MANUEL de la recrue.
 press('bid');
 let now=JSON.parse(cache.get('opfc-v08-local-dev')).game;
 assert.equal(now.auction.highestBid,5);
 assert.equal(now.auction.highestClub,first);
 assert.notEqual(now.auction.turn,first);
 press('pass');
 now=JSON.parse(cache.get('opfc-v08-local-dev')).game;
 const purchased=now.lastResult.cardId;
 assert.equal(now.lastResult.winner,first);
 assert.equal(now.teams.find(t=>t.club===first).roster.length,1);
 assert.match(root.innerHTML,/Recrue remportée/);
 press('close');
 assert.match(root.innerHTML,/placement-intro/);
 assert.match(root.innerHTML,new RegExp('data-top-club="'+first+'"'));
 assert.match(root.innerHTML,/slot-field-single/);
 assert.equal((root.innerHTML.match(/class="field-half /g)||[]).length,1);
 assert.match(root.innerHTML,/placement-metadata/);
 assert.match(root.innerHTML,/team-chip-details/);
 assert.match(root.innerHTML,/Sélection/);
 press('slot',{club:first,slot:'1'});
 now=JSON.parse(cache.get('opfc-v08-local-dev')).game;
 assert.equal(now.teams.find(t=>t.club===first).slots[1],purchased);
 assert.match(root.innerHTML,/slot-field/);
 press('continue-placement');
 assert.doesNotMatch(root.innerHTML,/placement-intro/);
 press('confirm-reset');
 assert.match(root.innerHTML,/Nouvelle partie/);
 press('close');
 press('confirm-reset');
 press('reset');
 assert.match(root.innerHTML,/La Grandline Cup/);
 assert.equal(cache.has('opfc-v08-local-dev'),false);
 delete globalThis.document;delete globalThis.localStorage;
});
